#include <stdio.h>


int main() {
	printf("Hello, World!\n");
   
   int integerNum = 42;
   printf("Integer: %i\n", integerNum);
   
   float floatingNum = 3.14;
   printf("Float: %f\n", floatingNum);

   double doubleNum = 33.1144;
   printf("Double Float: %lf\n", doubleNum);

   char letter = 'A';
   printf("Character: %c\n", letter);

   char characterArray[] = "Hello Strings!";
   printf("String: %s\n", characterArray);

   
    

	return 0;
}
